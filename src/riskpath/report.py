"""Markdown report built from the summary dict (so report and JSON never disagree)."""

from __future__ import annotations

from datetime import date
from typing import Any


def _d(iso: str | None) -> str:
    if not iso:
        return "n/a"
    return date.fromisoformat(iso).strftime("%a %d %b %Y")


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x:.1%}"


def build_markdown(s: dict[str, Any], img_rel: str = "../docs/img") -> str:
    det, sim, mar, tgt = s["deterministic"], s["simulation"], s["margin"], s["target"]
    st, cor, rev = s["settings"], s["correlation"], s["risk_events"]
    lines: list[str] = []
    w = lines.append
    w(f"# Schedule risk report: {s['project']}")
    w("")
    w(
        f"{s['n_tasks']} tasks, {st['iterations']:,} Monte Carlo iterations (seed {st['seed']}), "
        f"PERT-beta lambda = {st['pert_lambda']:g}, Gaussian copula rho = {st['rho']:g}. "
        f"Start {_d(st['start_date'])}; calendar: {st['calendar']} ({len(st['holidays'])} holidays)."
    )
    w("")
    w("> Synthetic example plan generated by `riskpath.sample`. Numbers below are computed by this run.")
    w("")
    w("## Headline")
    w("")
    w("| Measure | Working days | Finish date |")
    w("|---|---:|---|")
    w(f"| Deterministic CPM (most-likely) | {det['duration_days']:.0f} | {_d(det['finish_date'])} |")
    w(f"| P50 | {sim['p50_days']:.1f} | {_d(sim['p50_date'])} |")
    w(f"| P80 | {sim['p80_days']:.1f} | {_d(sim['p80_date'])} |")
    w(f"| P95 | {sim['p95_days']:.1f} | {_d(sim['p95_date'])} |")
    w(f"| Mean (std) | {sim['mean_days']:.1f} ({sim['std_days']:.1f}) | |")
    if tgt:
        w(f"| Target | {tgt['workdays']} | {_d(tgt['date'])} |")
    w("")
    w(f"- Probability of meeting the deterministic date: **{_pct(det['probability_of_meeting'])}**.")
    if tgt:
        w(
            f"- Probability of meeting the target ({_d(tgt['date'])}): **{_pct(tgt['probability'])}** "
            f"(independent tasks: {_pct(tgt['probability_independent'])}; "
            f"without discrete risk events: {_pct(tgt['probability_without_risk_events'])})."
        )
    w(
        f"- Recommended schedule margin: **{mar['recommended_days']} working days** "
        f"(P80 minus deterministic = {mar['raw_days']:.1f} d, {mar['pct_of_deterministic']:.1f}% of the plan). "
        f"Commit to {_d(mar['commit_date'])} rather than {_d(det['finish_date'])}."
    )
    w(
        f"- Merge bias: CPM on PERT-mean durations gives {det['pert_mean_duration_days']:.1f} d, but the "
        f"simulated mean without risk events is {s['merge_bias']['days']:.1f} d longer, because parallel "
        "paths converge and the latest one wins."
    )
    w(
        f"- Discrete risk events add {rev['p80_added_by_risk_events_days']:.1f} d at P80 "
        f"(P80 without them: {rev['p80_without_risk_events_days']:.1f} d)."
    )
    w(
        f"- Correlation: with rho = {cor['rho']:g} the P5-P95 spread is "
        f"{cor['p5_p95_spread_correlated_days']:.1f} d versus {cor['p5_p95_spread_independent_days']:.1f} d "
        f"if tasks were independent (P80 {cor['p80_correlated_days']:.1f} d vs {cor['p80_independent_days']:.1f} d)."
    )
    w("")
    w(f"![S-curve]({img_rel}/s_curve.png)")
    w("")
    w("## Deterministic critical path")
    w("")
    names = {t["id"]: t["name"] for t in s["tasks"]}
    w(" -> ".join(f"{tid} {names[tid]}" for tid in det["critical_path"]))
    w("")
    w(f"![Gantt]({img_rel}/gantt.png)")
    w("")
    w("## Criticality and sensitivity")
    w("")
    if s["near_critical_tasks"]:
        w(
            "Near-critical tasks (float > 0 in the deterministic plan, but critical in at least 20% of "
            "iterations): " + ", ".join(f"{t} {names[t]}" for t in s["near_critical_tasks"]) + "."
        )
        w("")
    w("| Task | Name | O / M / P (d) | Risk event | Total float (d) | Criticality index | Spearman rho (rho = 0 run) |")
    w("|---|---|---|---|---:|---:|---:|")
    for t in sorted(s["tasks"], key=lambda r: (-r["criticality_index"], r["id"])):
        risk = (
            f"{t['risk_event_prob']:.0%} x {t['risk_event_days']:g} d" if t["risk_event_prob"] > 0 else "none"
        )
        w(
            f"| {t['id']} | {t['name']} | {t['optimistic']:g} / {t['most_likely']:g} / {t['pessimistic']:g} | "
            f"{risk} | {t['total_float']:.0f} | {t['criticality_index']:.1%} | {t['sensitivity_spearman']:.2f} |"
        )
    w("")
    w(f"![Criticality]({img_rel}/criticality.png)")
    w("")
    w(f"![Tornado]({img_rel}/tornado.png)")
    w("")
    w("## Distribution")
    w("")
    w(f"![Histogram]({img_rel}/histogram.png)")
    w("")
    w("## How to read this")
    w("")
    w("- The deterministic date assumes every task hits its most-likely estimate. It is a planning")
    w("  anchor, not a forecast; its probability is shown above.")
    w("- Criticality index is the share of iterations in which a task had zero total float.")
    w("- Sensitivity is the Spearman rank correlation between a task's sampled duration and the")
    w("  project finish, computed on the independent (rho = 0) run with the same random numbers so a")
    w("  shared correlation factor does not inflate every task. High values mark the estimates most")
    w("  worth refining.")
    w("- The margin recommendation is the gap between the P80 and the deterministic finish, rounded")
    w("  up to whole working days.")
    w("")
    return "\n".join(lines)
